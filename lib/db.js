import fs from 'fs/promises';
import path from 'path';
import crypto from 'crypto';
const dir = path.join(process.cwd(), 'data');
const read = async (n, d) => { try { return JSON.parse(await fs.readFile(path.join(dir, n), 'utf8')); } catch { return d; } };
const write = (n, v) => fs.writeFile(path.join(dir, n), JSON.stringify(v, null, 2));
export const getSite = () => read('site.json', {});
export const saveSite = (v) => write('site.json', v);
export const getMsgs = () => read('messages.json', []);
export const saveMsgs = (v) => write('messages.json', v);
export const uploadDir = path.join(dir, 'uploads');
export const token = () => crypto.createHash('sha256').update((process.env.ADMIN_PASSWORD || '') + ':portfolio').digest('hex');
export const isAdmin = (req) => !!process.env.ADMIN_PASSWORD && req.cookies.get('admin')?.value === token();
